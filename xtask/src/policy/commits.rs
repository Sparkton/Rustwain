//! `CommitTrailers`: no AI co-author or attribution lines.

use crate::report::{Check, Finding};

const SHA_PREFIX_LEN: usize = 10;

const CO_AUTHOR_TRAILER: &str = "co-authored-by:";
const ANTHROPIC_NOREPLY: &str = "noreply@anthropic.com";
const GENERATED_PHRASES: &[&str] = &["generated with", "generated by"];
/// The robot face emoji that opens "generated with ..." lines.
const ROBOT_EMOJI: char = '\u{1F916}';

/// Matched case-insensitively as substrings, so `GPT-4` and `Copilot` both count.
const AI_NAMES: &[&str] = &[
    "claude",
    "anthropic",
    "openai",
    "chatgpt",
    "gpt",
    "copilot",
    "gemini",
    "codex",
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CommitMessage {
    pub sha: String,
    pub message: String,
}

impl CommitMessage {
    pub fn new(sha: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            sha: sha.into(),
            message: message.into(),
        }
    }
}

pub fn commit_trailers(commits: &[CommitMessage]) -> Vec<Finding> {
    commits
        .iter()
        .flat_map(|commit| {
            let sha: String = commit.sha.chars().take(SHA_PREFIX_LEN).collect();
            commit
                .message
                .lines()
                .map(str::trim)
                .filter(|line| is_ai_attribution(line))
                .map(move |line| {
                    Finding::error(
                        Check::CommitTrailers,
                        None,
                        format!(
                            "commit {sha}: AI attribution line `{line}`; AGENTS.md forbids AI \
                             co-author or attribution lines"
                        ),
                    )
                })
        })
        .collect()
}

fn is_ai_attribution(line: &str) -> bool {
    let lower = line.to_lowercase();
    let names_an_ai = |text: &str| AI_NAMES.iter().any(|name| text.contains(name));
    lower
        .strip_prefix(CO_AUTHOR_TRAILER)
        .is_some_and(names_an_ai)
        || lower.contains(ANTHROPIC_NOREPLY)
        || (GENERATED_PHRASES
            .iter()
            .any(|phrase| lower.contains(phrase))
            && names_an_ai(&lower))
        || line.starts_with(ROBOT_EMOJI)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SHA: &str = "0123456789abcdef0123456789abcdef01234567";

    #[test]
    fn human_co_author_and_ordinary_lines_pass() {
        let message = "Add the parser\n\nGenerated fixtures live in tests/.\n\n\
                       Co-authored-by: Jane Doe <jane@example.com>\n";

        let findings = commit_trailers(&[CommitMessage::new(SHA, message)]);

        assert_eq!(findings, []);
    }

    #[test]
    fn ai_co_author_and_attribution_lines_are_errors_without_a_location() {
        let offending = [
            "Co-Authored-By: Claude Sonnet <noreply@anthropic.com>",
            "co-authored-by: Some Bot <bot@example.com> (GitHub Copilot)",
            "Signed-off-by: Bot <noreply@anthropic.com>",
            "Generated with [Claude Code](https://claude.com/claude-code)",
            "generated by ChatGPT",
            "\u{1F916} Generated automatically",
        ];
        let message = format!("Add the parser\n\n{}\n", offending.join("\n"));

        let findings = commit_trailers(&[CommitMessage::new(SHA, message)]);

        let expected = offending.map(|line| {
            Finding::error(
                Check::CommitTrailers,
                None,
                format!(
                    "commit 0123456789: AI attribution line `{line}`; AGENTS.md forbids AI \
                     co-author or attribution lines"
                ),
            )
        });
        assert_eq!(findings, expected);
    }
}
