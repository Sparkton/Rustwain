//! `CommitTrailers`: no AI co-author or attribution lines.
//!
//! A trailer (`Key: value`) in the message body is flagged by the identity in its value,
//! not by a substring: `Claude Dupont <claude@example.fr>` is a person,
//! `Claude Opus 5.5 <noreply@anthropic.com>` is not. The subject line is never read as
//! a trailer, so `docs: Claude` passes; only `Co-authored-by` is checked there too.
//! Free text is flagged only when a line opens with the robot emoji, or with
//! "generated with/by" and names an AI. Those two rules apply to every line.

use crate::report::{Check, Finding};

const SHA_PREFIX_LEN: usize = 10;

/// The one trailer key that is checked on the subject line as well as in the body.
const CO_AUTHOR_KEY: &str = "co-authored-by";

/// The robot face emoji, which opens "generated with ..." footers.
const ROBOT_EMOJI: char = '\u{1F916}';
/// Skipped before looking for the "generated with/by" phrase: a footer may be a bullet,
/// quote, emphasis or have the emoji in front.
const FOOTER_MARKS: &[char] = &[ROBOT_EMOJI, '*', '_', '>', '-'];
const GENERATED_PHRASES: &[&str] = &["generated with", "generated by"];

/// Whole words that name an AI, matched without regard to case. A substring never counts.
const AI_WORDS: &[&str] = &[
    "claude",
    "anthropic",
    "openai",
    "chatgpt",
    "gpt",
    "copilot",
    "gemini",
    "codex",
];

/// Email domains of AI vendors. Their subdomains count too.
const AI_EMAIL_DOMAINS: &[&str] = &[
    "anthropic.com",
    "openai.com",
    "cursor.com",
    "cognition.ai",
    "aider.chat",
];

/// GitHub noreply addresses are `<account>@` or `<id>+<account>@` this domain.
const GITHUB_NOREPLY_DOMAIN: &str = "users.noreply.github.com";
const COPILOT_ACCOUNT: &str = "copilot";
const BOT_ACCOUNT_SUFFIX: &str = "[bot]";

/// AI product names, as the words of a trailer's name.
const AI_PRODUCTS: &[&[&str]] = &[
    &["claude"],
    &["claude", "code"],
    &["chatgpt"],
    &["gpt"],
    &["copilot"],
    &["github", "copilot"],
    &["gemini"],
    &["codex"],
    &["cursor"],
    &["cursor", "agent"],
    &["aider"],
];

/// Words that may follow a product name, besides versions such as `5.5`.
const MODEL_WORDS: &[&str] = &["opus", "sonnet", "haiku", "fable", "agent"];

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CommitMessage {
    pub sha: String,
    pub message: String,
}

impl CommitMessage {
    pub fn new(sha: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            sha: sha.into(),
            message: message.into(),
        }
    }
}

/// Where a line sits in a commit message.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Part {
    Subject,
    Body,
}

pub fn commit_trailers(commits: &[CommitMessage]) -> Vec<Finding> {
    commits
        .iter()
        .flat_map(|commit| {
            let sha: String = commit.sha.chars().take(SHA_PREFIX_LEN).collect();
            // The first line is the subject, even when no blank line follows it, so a
            // trailer-like line right under it still counts as body.
            let mut lines = commit.message.lines();
            let subject = lines.next().into_iter().map(|line| (Part::Subject, line));
            let body = lines.map(|line| (Part::Body, line));
            subject
                .chain(body)
                .map(|(part, line)| (part, line.trim()))
                .filter(|&(part, line)| is_ai_attribution(line, part))
                .map(move |(_, line)| {
                    Finding::error(
                        Check::CommitTrailers,
                        None,
                        format!(
                            "commit {sha}: AI attribution line `{line}`; AGENTS.md forbids AI \
                             co-author or attribution lines"
                        ),
                    )
                })
        })
        .collect()
}

fn is_ai_attribution(line: &str, part: Part) -> bool {
    line.starts_with(ROBOT_EMOJI)
        || is_generated_footer(line)
        || trailer(line).is_some_and(|(key, value)| {
            let is_checked_here = part == Part::Body || key.eq_ignore_ascii_case(CO_AUTHOR_KEY);
            is_checked_here && identifies_an_ai(value)
        })
}

/// "Generated with Claude Code" and similar, but not a subject that merely quotes it.
fn is_generated_footer(line: &str) -> bool {
    let text = line.trim_start_matches(|c: char| c.is_whitespace() || FOOTER_MARKS.contains(&c));
    let starts_with_phrase = GENERATED_PHRASES.iter().any(|phrase| {
        text.get(..phrase.len())
            .is_some_and(|start| start.eq_ignore_ascii_case(phrase))
    });
    starts_with_phrase
        && words(text).any(|word| AI_WORDS.iter().any(|ai| ai.eq_ignore_ascii_case(word)))
}

/// The key and value of a `Key: value` line, where the key is `[A-Za-z][A-Za-z-]*`.
fn trailer(line: &str) -> Option<(&str, &str)> {
    let (key, value) = line.split_once(':')?;
    let mut key_chars = key.chars();
    let is_key = key_chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        && key_chars.all(|c| c.is_ascii_alphabetic() || c == '-');
    let value = value.trim();
    (is_key && !value.is_empty()).then_some((key, value))
}

/// A value is `Name <email>` or just a name. Text after the closing `>` is ignored.
fn identifies_an_ai(value: &str) -> bool {
    match value.split_once('<') {
        Some((name, rest)) => {
            let email = rest.split_once('>').map(|(email, _)| email);
            is_ai_name(name) || email.is_some_and(is_ai_email)
        }
        None => is_ai_name(value),
    }
}

/// An AI product name, optionally followed by model or version words: `Claude`,
/// `Cursor Agent`, `Claude Opus 5.5`, but not `Claude Dupont`.
fn is_ai_name(name: &str) -> bool {
    let words: Vec<&str> = words(name).collect();
    AI_PRODUCTS.iter().any(|product| {
        words
            .split_at_checked(product.len())
            .is_some_and(|(head, rest)| {
                head.iter()
                    .zip(*product)
                    .all(|(word, name)| word.eq_ignore_ascii_case(name))
                    && rest.iter().all(|word| is_model_word(word))
            })
    })
}

fn is_model_word(word: &str) -> bool {
    let is_version = word.chars().all(|c| c.is_ascii_digit() || c == '.')
        && word.chars().any(|c| c.is_ascii_digit());
    is_version
        || MODEL_WORDS
            .iter()
            .any(|model| model.eq_ignore_ascii_case(word))
}

fn is_ai_email(email: &str) -> bool {
    let email = email.trim().to_ascii_lowercase();
    let Some((local, domain)) = email.rsplit_once('@') else {
        return false;
    };
    let is_vendor = AI_EMAIL_DOMAINS.iter().any(|vendor| {
        domain == *vendor
            || domain
                .strip_suffix(vendor)
                .is_some_and(|prefix| prefix.ends_with('.'))
    });
    is_vendor || (domain == GITHUB_NOREPLY_DOMAIN && is_ai_github_account(local))
}

fn is_ai_github_account(local_part: &str) -> bool {
    let account = local_part
        .rsplit_once('+')
        .map_or(local_part, |(_, account)| account);
    account == COPILOT_ACCOUNT || account.ends_with(BOT_ACCOUNT_SUFFIX)
}

/// Alphanumeric words of `text`. Dots inside a word stay, so `5.5` is one word.
fn words(text: &str) -> impl Iterator<Item = &str> {
    text.split(|c: char| !(c.is_ascii_alphanumeric() || c == '.'))
        .map(|word| word.trim_matches('.'))
        .filter(|word| !word.is_empty())
}

#[cfg(test)]
mod tests {
    use super::*;

    const SHA: &str = "0123456789abcdef0123456789abcdef01234567";

    fn flagged_lines(lines: &[&str]) -> Vec<Finding> {
        let message = format!("Add the parser\n\n{}\n", lines.join("\n"));
        commit_trailers(&[CommitMessage::new(SHA, message)])
    }

    fn attribution_error(line: &str) -> Finding {
        Finding::error(
            Check::CommitTrailers,
            None,
            format!(
                "commit 0123456789: AI attribution line `{line}`; AGENTS.md forbids AI \
                 co-author or attribution lines"
            ),
        )
    }

    #[test]
    fn people_and_quotes_of_attribution_text_pass() {
        let lines = [
            "Co-authored-by: Jane Doe <jane@example.com>",
            "Co-authored-by: Claude Dupont <claude@example.fr>",
            "Reviewed-by: Gemini Smith <gemini@example.org>",
            "Signed-off-by: Jane Doe <jane@example.com>",
            "Fixes: #12",
            "Note: the Claude API changed",
            "Generated fixtures live in tests/.",
            "Generated by Gptolemy's script",
            "policy: reject 'Generated with Claude Code' footers",
        ];

        let findings = flagged_lines(&lines);

        assert_eq!(findings, []);
    }

    #[test]
    fn ai_trailers_footers_and_emoji_lines_are_errors_without_a_location() {
        let offending = [
            "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
            "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
            "Co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>",
            "Co-authored-by: renovate[bot] <29139614+renovate[bot]@users.noreply.github.com>",
            "Co-authored-by: GitHub Copilot",
            "Signed-off-by: Bot <noreply@anthropic.com>",
            "Assisted-by: Claude",
            "Generated-by: Claude",
            "Generated with [Claude Code](https://claude.com/claude-code)",
            "> *Generated by ChatGPT*",
            "\u{1F916} Generated with Claude Code",
            "\u{1F916} Generated automatically",
        ];

        let findings = flagged_lines(&offending);

        assert_eq!(findings, offending.map(attribution_error));
    }

    // A subject such as `docs: Claude` looks like `Key: value` but is not a trailer.
    #[test]
    fn a_subject_naming_an_ai_passes_but_the_same_text_as_a_body_trailer_fails() {
        let subject_only = CommitMessage::new(SHA, "docs: Claude\n\nExplain the new flow.\n");
        let with_trailer = CommitMessage::new(SHA, "docs: Claude\n\nAssisted-by: Claude\n");

        let subject_findings = commit_trailers(&[subject_only]);
        let trailer_findings = commit_trailers(&[with_trailer]);

        assert_eq!(subject_findings, []);
        assert_eq!(trailer_findings, [attribution_error("Assisted-by: Claude")]);
    }

    #[test]
    fn a_co_author_line_is_flagged_on_the_subject_too_but_a_person_is_not() {
        let ai = CommitMessage::new(SHA, "Co-authored-by: Claude <noreply@anthropic.com>\n");
        let person = CommitMessage::new(SHA, "Co-authored-by: Jane Doe <jane@example.com>\n");

        let findings = commit_trailers(&[ai, person]);

        assert_eq!(
            findings,
            [attribution_error(
                "Co-authored-by: Claude <noreply@anthropic.com>"
            )]
        );
    }
}
